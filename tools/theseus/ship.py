#!/usr/bin/env python3
"""Ship gated Theseus rewrites into the game build.

Usage (from the repo root):
    python3 tools/theseus/ship.py            # regenerate tools/theseus/shipped/theseus_overrides.cpp
    python3 tools/theseus/ship.py --confirm  # after the in-game check: ledger rows gated -> shipped

The generated file #includes every rewrite whose ledger row is `gated` or `shipped` (so the
game runs exactly the code the gate tested) and defines registerTheseusOverrides(), which the
probe calls after the generated, supplemental and native registrations. Each override takes
only the function's entry address; the table's internal resume slots keep the original, which
a rewrite never needs (rewrites don't yield mid-function). Set SIMS_THESEUS=0 to run the
originals instead (A/B without a rebuild). Call counts are printed when the game exits.
Rebuild afterwards: cmake --build build/probe --target sims_boot_probe
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
LEDGER = os.path.join(HERE, "batch/ledger.tsv")
OUT = os.path.join(HERE, "shipped/theseus_overrides.cpp")

TEMPLATE = """// Generated by tools/theseus/ship.py from tools/theseus/batch/ledger.tsv - do not edit.
// Every rewrite here passed tools/theseus/gate.py. The sources are included as-is, so the game
// runs exactly the tested code.
#include <atomic>
#include <cstdio>
#include <cstdlib>

#include "theseus.h"

{includes}

namespace
{{
    struct Override
    {{
        const char *name;
        uint32_t address;
        PS2Runtime::RecompiledFunction fn;
    }};

    std::atomic<uint64_t> g_calls[{count}];

{wrappers}

    const Override kOverrides[] = {{
{table}
    }};
}}

void registerTheseusOverrides(PS2Runtime &runtime)
{{
    const char *env = std::getenv("SIMS_THESEUS");
    if (env && env[0] == '0')
    {{
        std::printf("[theseus] SIMS_THESEUS=0: running the recompiled originals\\n");
        return;
    }}
    for (const Override &o : kOverrides)
        runtime.registerFunction(o.address, o.fn);
    std::printf("[theseus] %zu rewrites active (SIMS_THESEUS=0 to disable)\\n",
                sizeof(kOverrides) / sizeof(kOverrides[0]));
}}

void printTheseusStats()
{{
    for (size_t i = 0; i < sizeof(kOverrides) / sizeof(kOverrides[0]); ++i)
        std::printf("[theseus] %-40s 0x%06x calls=%llu\\n", kOverrides[i].name, kOverrides[i].address,
                    static_cast<unsigned long long>(g_calls[i].load(std::memory_order_relaxed)));
}}
"""


def read_ledger():
    with open(LEDGER) as f:
        return list(csv.DictReader(f, delimiter="\t"))


def main():
    rows = read_ledger()
    if "--confirm" in sys.argv:
        n = 0
        for r in rows:
            if r["status"] == "gated":
                r["status"] = "shipped"
                n += 1
        with open(LEDGER, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()), delimiter="\t", lineterminator="\n")
            w.writeheader()
            w.writerows(rows)
        print(f"{n} ledger rows gated -> shipped")
        return
    ship = [r for r in rows if r["status"] in ("gated", "shipped") and r["gate"].startswith("PASS")]
    ship.sort(key=lambda r: r["name"])
    includes, wrappers, table = [], [], []
    for i, r in enumerate(ship):
        name = r["name"]
        calls_out = "g.call(" in open(os.path.join(HERE, "rewrites", name + ".cpp")).read()
        addr = int(re.search(r"_([0-9a-fA-F]{6,8})$", name).group(1), 16)
        # Each rewrite in its own namespace: their file-local helpers (constants, lambdas) may
        # share names. theseus.h is already included above, so its #pragma once skips it here.
        includes.append(f"namespace rw{i}\n{{\n#include \"rewrites/{name}.cpp\"\n}}")
        wrappers.append(f"    void call_{i}(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)\n"
                        f"    {{\n        g_calls[{i}].fetch_add(1, std::memory_order_relaxed);\n"
                        (f"        ps2x::native::runOnFiber(*runtime, rw{i}::{name}, rdram, ctx);  // calls guest code\n    }}"
                         if calls_out else f"        rw{i}::{name}(rdram, ctx, runtime);\n    }}"))
        table.append(f'        {{"{name}", 0x{addr:06x}u, call_{i}}},')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    text = TEMPLATE.format(includes="\n".join(includes), count=max(1, len(ship)),
                           wrappers="\n".join(wrappers), table="\n".join(table))
    with open(OUT, "w") as f:
        f.write(text)
    print(f"{len(ship)} rewrites -> {os.path.relpath(OUT, REPO)}")


if __name__ == "__main__":
    main()
